import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const source = new URL('docs/CITATIONS.csl.json', root)
const target = new URL('src/types/citation-ids.generated.ts', root)

const entries = JSON.parse(readFileSync(source, 'utf8'))
const ids = entries.map((entry) => entry.id).sort()

const duplicates = ids.filter((id, index) => ids.indexOf(id) !== index)
if (duplicates.length > 0) throw new Error(`duplicate citekeys: ${duplicates.join(', ')}`)

const malformed = ids.filter((id) => !/^[a-z0-9][a-z0-9-]*$/.test(id))
if (malformed.length > 0) throw new Error(`malformed citekeys: ${malformed.join(', ')}`)

const body = `// GENERATED by scripts/generate-citations.mjs from docs/CITATIONS.csl.json
// Do not edit by hand. Run \`bun run generate\` after changing the CSL-JSON
export const CITATION_IDS = [
${ids.map((id) => `  '${id}',`).join('\n')}
] as const

export type CitationId = (typeof CITATION_IDS)[number]
`

writeFileSync(target, body)
console.log(`wrote ${ids.length} citekeys to ${fileURLToPath(target)}`)

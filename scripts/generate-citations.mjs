import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const source = new URL('docs/CITATIONS.csl.json', root)
const target = new URL('src/types/citation-ids.generated.ts', root)

const entries = JSON.parse(readFileSync(source, 'utf8'))
const ids = entries.map((entry) => entry.id).sort()

const duplicates = ids.filter((id, index) => ids.indexOf(id) !== index)
if (duplicates.length > 0) throw new Error(`duplicate citekeys: ${duplicates.join(', ')}`)

const malformed = ids.filter((id) => !/^[a-z0-9][a-z0-9-]*$/.test(id))
if (malformed.length > 0) throw new Error(`malformed citekeys: ${malformed.join(', ')}`)

// a quote is the source's own words, a locator string and the index of the claim it backs
const quoteFlaw = (quote, claimCount) => {
  if (typeof quote?.text !== 'string' || quote.text.trim() === '') {
    return 'text is not a non-empty string'
  }
  if (typeof quote.locator !== 'string') return 'locator is not a string'
  if (!Number.isInteger(quote.claim) || quote.claim < 0 || quote.claim >= claimCount) {
    return `claim ${JSON.stringify(quote.claim)} is not an index into the ${claimCount} backsClaims`
  }
  return null
}

for (const entry of entries) {
  const quotes = entry.custom?.quotes
  if (quotes === undefined) continue
  if (!Array.isArray(quotes)) throw new Error(`${entry.id}: custom.quotes is not a list`)
  quotes.forEach((quote, index) => {
    const flaw = quoteFlaw(quote, entry.custom.backsClaims?.length ?? 0)
    if (flaw !== null) throw new Error(`${entry.id}: custom.quotes[${index}] ${flaw}`)
  })
}

const body = `// GENERATED by scripts/generate-citations.mjs from docs/CITATIONS.csl.json
// Do not edit by hand. Run \`bun run generate\` after changing the CSL-JSON
export const CITATION_IDS = [
${ids.map((id) => `  '${id}',`).join('\n')}
] as const

export type CitationId = (typeof CITATION_IDS)[number]
`

writeFileSync(target, body)
console.log(`wrote ${ids.length} citekeys to ${fileURLToPath(target)}`)

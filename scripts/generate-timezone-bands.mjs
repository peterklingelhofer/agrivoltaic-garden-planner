/**
 * Generates `src/data/timezone-bands.ts`: which latitude band each IANA time zone sits in, every
 * zone's coordinate, and a nearest-zone lookup by point.
 *
 *   node scripts/generate-timezone-bands.mjs
 *
 * The app opens on a worked example, and an example baked at 42 N is the wrong sun for a
 * visitor in Phoenix or Bergen. A browser won't say where it is without asking permission,
 * but it will say its time zone, and tzdb records a coordinate for every zone it defines. So the
 * band is READ from `zone.tab`: "America/Denver" and
 * "America/Phoenix" share a prefix and six degrees of latitude, and any table written by hand
 * from zone names would get pairs like that wrong.
 *
 * Only the zones that are NOT in the default band are written out, which is what keeps the band
 * table small. A zone this build has never heard of falls to the default, which is the same thing
 * that happens when `Intl` is unavailable.
 *
 * The points table carries every zone (all 418), because it backs a second job: when nothing
 * upstream names a time zone for a place, the nearest zone.tab city stands in for it, which is
 * right far more often than a whole-hour guess from the longitude alone (see `nearestTimezone`
 * in the generated file, and `timezoneFor` in `src/data/geocode.ts`)
 */
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'src', 'data', 'timezone-bands.ts')
const ZONE_TAB = process.env.ZONE_TAB ?? '/usr/share/zoneinfo/zone.tab'

/** ISO 6709 as tzdb writes it: +DDMM[SS] latitude, then longitude. Only latitude is wanted */
const latitudeOf = (coordinates) => {
  const match = /^([+-])(\d{2})(\d{2})(\d{2})?/.exec(coordinates)
  if (match === null) return null
  const degrees = Number(match[2]) + Number(match[3]) / 60 + Number(match[4] ?? 0) / 3600
  return match[1] === '-' ? -degrees : degrees
}

/** The longitude half of the same ISO 6709 string: ±DDDMM[SS], right after the latitude */
const longitudeOf = (coordinates) => {
  const match = /^[+-]\d{2}\d{2}(?:\d{2})?([+-])(\d{3})(\d{2})(\d{2})?/.exec(coordinates)
  if (match === null) return null
  const degrees = Number(match[2]) + Number(match[3]) / 60 + Number(match[4] ?? 0) / 3600
  return match[1] === '-' ? -degrees : degrees
}

const rows = (await readFile(ZONE_TAB, 'utf8'))
  .split('\n')
  .filter((line) => line.length > 0 && !line.startsWith('#'))
  .map((line) => line.split('\t'))

const bandOf = (latitude) => {
  const away = Math.abs(latitude)
  if (away < 35) return 'low'
  if (away > 50) return 'high'
  return 'temperate'
}

/**
 * `low` is the default because it's where most zones are (235 of 418 against 96 temperate and
 * 87 high), so omitting it makes the smallest table, and because a zone this build has never
 * heard of is more likely to be a new low-latitude one than anything else
 */
const DEFAULT_BAND = 'low'
const entries = []
for (const [, coordinates, zone] of rows) {
  const latitude = latitudeOf(coordinates ?? '')
  if (latitude === null || zone === undefined) continue
  const band = bandOf(latitude)
  if (band !== DEFAULT_BAND) entries.push([zone, band])
}
entries.sort(([a], [b]) => a.localeCompare(b))

/** Every zone with a usable coordinate, which is all 418: nothing here falls to a default */
const points = []
for (const [codes, coordinates, zone] of rows) {
  const latitude = latitudeOf(coordinates ?? '')
  const longitude = longitudeOf(coordinates ?? '')
  if (latitude === null || longitude === null || zone === undefined) continue
  // the ISO 3166 codes zone.tab lists for the zone, comma-separated where a zone serves several
  points.push([zone, Number(latitude.toFixed(4)), Number(longitude.toFixed(4)), codes ?? ''])
}
points.sort(([a], [b]) => a.localeCompare(b))

const body = entries.map(([zone, band]) => `  '${zone}': '${band}',`).join('\n')
const pointsBody = points
  .map(
    ([zone, latitude, longitude, codes]) =>
      `  ['${zone}', ${String(latitude)}, ${String(longitude)}, '${codes}'],`,
  )
  .join('\n')
const source = `// Generated by scripts/generate-timezone-bands.mjs from tzdb zone.tab. Do not edit.
// ${String(rows.length)} zones read, ${String(entries.length)} outside the ${DEFAULT_BAND} band,
// ${String(points.length)} on the points table.

export type LatitudeBand = 'low' | 'temperate' | 'high'

/** Zones in the default band are omitted, which is most of the table */
export const TIMEZONE_BANDS: Readonly<Record<string, LatitudeBand>> = {
${body}
}

export const DEFAULT_BAND: LatitudeBand = '${DEFAULT_BAND}'

/**
 * The band a browser is probably in. Wrong for a visitor whose zone spans the boundary, and
 * harmless when it is: the example names the place it was baked for and offers the others
 */
export const bandForTimezone = (timezone: string | null): LatitudeBand =>
  timezone === null ? DEFAULT_BAND : (TIMEZONE_BANDS[timezone] ?? DEFAULT_BAND)

/**
 * Every zone zone.tab defines, sorted by name, at the coordinate it publishes for that zone, with
 * the ISO 3166 country codes it lists for the zone (comma-separated where one zone serves several)
 */
export const TIMEZONE_POINTS: readonly (readonly [
  zone: string,
  latitudeDeg: number,
  longitudeDeg: number,
  countries: string,
])[] = [
${pointsBody}
]

/**
 * The zone.tab zone nearest a point, by equirectangular distance: flat enough at this scale,
 * since all it has to do is rank ~400 named points. The
 * longitude gap is scaled by the cosine of the mean latitude, so a degree of longitude counts for
 * less near the poles than at the equator, and wrapped into [-180, 180] so the antimeridian is not
 * a false half-world gap. Null only when the table above is empty.
 *
 * With a country code, only that country's zones are ranked, and every zone is ranked only when the
 * code matches none. zone.tab records one point for all of India, Kolkata, in the far east, so the
 * nearest point to Mumbai is Karachi's and the nearest to Delhi is Kathmandu's; a geocoder names
 * the country, and within it the answer is right. Without a code the rule is still wrong where a
 * point sits near a border and the nearest city is a neighbor's, a rarer failure than the
 * whole-hour longitude guess, which is wrong across whole countries
 */
export const nearestTimezone = (
  latitudeDeg: number,
  longitudeDeg: number,
  countryCode: string | null = null,
): string | null => {
  const code = countryCode === null ? null : countryCode.toUpperCase()
  const within =
    code === null
      ? []
      : TIMEZONE_POINTS.filter(([, , , countries]) => countries.split(',').includes(code))
  const candidates = within.length > 0 ? within : TIMEZONE_POINTS
  let nearest = null
  let nearestDistance = Number.POSITIVE_INFINITY
  for (const [zone, pointLatitudeDeg, pointLongitudeDeg] of candidates) {
    const dLat = pointLatitudeDeg - latitudeDeg
    const dLon = (((pointLongitudeDeg - longitudeDeg + 180) % 360) + 360) % 360 - 180
    const meanLatitudeRad = ((pointLatitudeDeg + latitudeDeg) / 2) * (Math.PI / 180)
    const scaledDLon = dLon * Math.cos(meanLatitudeRad)
    const distance = dLat * dLat + scaledDLon * scaledDLon
    if (distance < nearestDistance) {
      nearestDistance = distance
      nearest = zone
    }
  }
  return nearest
}
`
await writeFile(OUT, source)
process.stdout.write(
  `${OUT}: ${String(entries.length)} of ${String(rows.length)} zones outside ${DEFAULT_BAND}, ${String(points.length)} points\n`,
)

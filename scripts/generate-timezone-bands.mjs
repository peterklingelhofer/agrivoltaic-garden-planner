/**
 * Generates `src/data/timezone-bands.ts`: which latitude band each IANA time zone sits in.
 *
 *   node scripts/generate-timezone-bands.mjs
 *
 * The app opens on a worked example, and an example baked at 42 N is the wrong sun for a
 * visitor in Phoenix or Bergen. A browser will not say where it is without asking permission,
 * but it will say its time zone, and tzdb records a coordinate for every zone it defines. So the
 * band is READ from `zone.tab` rather than guessed from the name: "America/Denver" and
 * "America/Phoenix" share a prefix and six degrees of latitude, and any table written by hand
 * from zone names would get pairs like that wrong.
 *
 * Only the zones that are NOT in the default band are written out, which is what keeps the table
 * small. A zone this build has never heard of falls to the default, which is the same thing that
 * happens when `Intl` is unavailable.
 */
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'src', 'data', 'timezone-bands.ts')
const ZONE_TAB = process.env.ZONE_TAB ?? '/usr/share/zoneinfo/zone.tab'

/** ISO 6709 as tzdb writes it: +DDMM[SS] latitude, then longitude. Only latitude is wanted */
const latitudeOf = (coordinates) => {
  const match = /^([+-])(\d{2})(\d{2})(\d{2})?/.exec(coordinates)
  if (match === null) return null
  const degrees = Number(match[2]) + Number(match[3]) / 60 + Number(match[4] ?? 0) / 3600
  return match[1] === '-' ? -degrees : degrees
}

const rows = (await readFile(ZONE_TAB, 'utf8'))
  .split('\n')
  .filter((line) => line.length > 0 && !line.startsWith('#'))
  .map((line) => line.split('\t'))

const bandOf = (latitude) => {
  const away = Math.abs(latitude)
  if (away < 35) return 'low'
  if (away > 50) return 'high'
  return 'temperate'
}

/**
 * `low` is the default because it is where most zones are (235 of 418 against 96 temperate and
 * 87 high), so omitting it makes the smallest table, and because a zone this build has never
 * heard of is more likely to be a new low-latitude one than anything else
 */
const DEFAULT_BAND = 'low'
const entries = []
for (const [, coordinates, zone] of rows) {
  const latitude = latitudeOf(coordinates ?? '')
  if (latitude === null || zone === undefined) continue
  const band = bandOf(latitude)
  if (band !== DEFAULT_BAND) entries.push([zone, band])
}
entries.sort(([a], [b]) => a.localeCompare(b))

const body = entries.map(([zone, band]) => `  '${zone}': '${band}',`).join('\n')
const source = `// Generated by scripts/generate-timezone-bands.mjs from tzdb zone.tab. Do not edit.
// ${String(rows.length)} zones read, ${String(entries.length)} outside the ${DEFAULT_BAND} band.

export type LatitudeBand = 'low' | 'temperate' | 'high'

/** Zones in the default band are omitted, which is most of the table */
export const TIMEZONE_BANDS: Readonly<Record<string, LatitudeBand>> = {
${body}
}

export const DEFAULT_BAND: LatitudeBand = '${DEFAULT_BAND}'

/**
 * The band a browser is probably in. Wrong for a visitor whose zone spans the boundary, and
 * harmless when it is: the example names the place it was baked for and offers the others
 */
export const bandForTimezone = (timezone: string | null): LatitudeBand =>
  timezone === null ? DEFAULT_BAND : (TIMEZONE_BANDS[timezone] ?? DEFAULT_BAND)
`
await writeFile(OUT, source)
process.stdout.write(
  `${OUT}: ${String(entries.length)} of ${String(rows.length)} zones outside ${DEFAULT_BAND}\n`,
)

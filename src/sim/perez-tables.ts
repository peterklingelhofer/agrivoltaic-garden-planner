// Lower edges of the 8 Perez sky-clearness bins; eps < 1.065 is bin 0
export const PEREZ_EPSILON_EDGES: readonly number[] = [1.065, 1.23, 1.5, 1.95, 2.8, 4.5, 6.2]

export const PEREZ_KAPPA_RADIANS = 1.041

export const perezClearnessBin = (epsilon: number): number => {
  let bin = 0
  while (bin < PEREZ_EPSILON_EDGES.length && epsilon >= (PEREZ_EPSILON_EDGES[bin] ?? Infinity)) {
    bin += 1
  }
  return bin
}

